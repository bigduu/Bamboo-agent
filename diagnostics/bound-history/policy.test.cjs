const { readFileSync } = require('node:fs')
const { join } = require('node:path')
const { test } = require('node:test')
const assert = require('node:assert/strict')

const root = join(__dirname, '../..')
const workflow = readFileSync(join(root, '.github/workflows/supervisor-role-acceptance.yml'), 'utf8')
const browser = readFileSync(join(__dirname, 'browser.mjs'), 'utf8')
const seed = readFileSync(join(__dirname, 'seed.rs'), 'utf8')
const bounded = readFileSync(join(__dirname, 'bounded-cargo.py'), 'utf8')

test('dispatch is restricted to the authorized branch and exact inputs', () => {
  assert.match(workflow, /workflow_dispatch:/)
  assert.match(workflow, /refs\/heads\/bamboo\/diagnostic\/2396-bound-history-macos-20261030/)
  assert.match(workflow, /499e3e7769cb574d61699e8af85169e27f695125/)
  assert.match(workflow, /b730ed15c76e569024d096ab3a703bc3856a1074/)
  assert.match(workflow, /test "\$EXPECTED_CONTROLLER" = "\$DISPATCH_SOURCE"/)
  assert.doesNotMatch(workflow, /^  push:/m)
})
test('only a standard runner and no cache, artifact, publication or deployment', () => {
  assert.match(workflow, /runs-on: macos-15/)
  assert.match(workflow, /package-manager-cache: false/)
  assert.doesNotMatch(workflow, /upload-artifact|actions\/cache|rust-cache|npm publish|cargo publish|deploy/i)
  assert.match(workflow, /CARGO_BUILD_JOBS: '1'/)
  assert.match(bounded, /MIN_FREE = 2 \* 1024\*\*3/)
})
test('the fixture uses storage and the unknown case drops an actual response', () => {
  assert.match(seed, /SessionStoreV2::new/)
  assert.match(seed, /store\.save_session\(&session\)/)
  assert.match(browser, /const actual = await route\.fetch\(\{ maxRetries: 0 \}\)/)
  assert.match(browser, /route\.abort\('failed'\)/)
  assert.doesNotMatch(browser, /route\.fulfill\(/)
  assert.doesNotMatch(browser, /\/api\/v1\/(?:chat|execute)(?:\/|'|"|`)/)
  assert.match(browser, /target_observation_stale/)
  assert.match(browser, /bound_clear_evidence/)
})
